import nextEnv from "@next/env";
const { loadEnvConfig } = nextEnv;
import { drizzle } from "drizzle-orm/neon-http";
import { migrate } from "drizzle-orm/neon-http/migrator";
import { neon } from "@neondatabase/serverless";
import { crustCreditBudget } from "../src/server/research-provider";
loadEnvConfig(process.cwd());
if (!process.env.DATABASE_URL) throw new Error("Add DATABASE_URL to .env.local first.");
const client = neon(process.env.DATABASE_URL);
await migrate(drizzle(client), { migrationsFolder: "./drizzle" });
await client`insert into budgets(id,limit_cents,credit_limit_milli) values('research',0,${crustCreditBudget()*1000}) on conflict do nothing`;
console.log("Schema migrated. Credit ledger initialized only if new; existing allocations preserved.");
